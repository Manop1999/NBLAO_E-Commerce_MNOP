/**
 * Logic behind the local `pnpm auth:*` commands (scripts/auth.ts handles prompts and output). Every function
 * takes a client created by createDatabaseClient(), so assertLocalDatabase() has already accepted the target.
 */
import { randomBytes } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import type { PrismaClient } from '../generated/prisma/client.ts'
import { passwordPolicyError } from './accountTokens.ts'
import { recordAudit } from './audit.ts'
import { normalizeEmail } from './context.ts'
import { checkPasswordPolicy, type PasswordHasher } from './password.ts'
import { clearAllForAccount } from './mfaThrottle.ts'
import { isPrivilegedEmail, PRIVILEGED_EMAIL_SUFFIX } from './privilegedNamespace.ts'
import { revokeAllSessions } from './sessions.ts'

export const TOTP_KEY_VARIABLE = 'TOTP_ENCRYPTION_KEY'

/**
 * Adds a fresh TOTP_ENCRYPTION_KEY to the local .env file if it has none. Never prints or returns the key.
 * Returns 'exists' when a non-empty key is already there (it is never replaced: that would invalidate every
 * 2FA enrolment).
 */
export function ensureTotpKey(envFile: string): 'created' | 'exists' {
  if (!existsSync(envFile)) throw new Error(`${envFile} does not exist. Copy .env.example to .env first.`)
  const text = readFileSync(envFile, 'utf8')
  const line = text.split(/\r?\n/).find(entry => entry.trim().startsWith(`${TOTP_KEY_VARIABLE}=`))
  if (line && line.slice(line.indexOf('=') + 1).trim() !== '') return 'exists'
  const key = randomBytes(32).toString('base64')
  const withoutEmpty = line ? text.replace(line, '').replace(/\n{3,}/g, '\n\n') : text
  const separator = withoutEmpty.endsWith('\n') || withoutEmpty === '' ? '' : '\n'
  writeFileSync(
    envFile,
    `${withoutEmpty}${separator}\n# AES-256-GCM key for 2FA secrets (generated by pnpm auth:setup-keys). Never commit or share it;\n# replacing it invalidates every 2FA enrolment.\n${TOTP_KEY_VARIABLE}=${key}\n`,
    'utf8',
  )
  return 'created'
}

export class CliRefusal extends Error {
  constructor(message: string) {
    super(message)
    this.name = 'CliRefusal'
  }
}

/**
 * Creates the first Super Admin. Refuses when any Super Admin already exists (further admins come from the
 * Admin API). The account must change its password and enrol 2FA at first sign-in.
 */
export async function createFirstSuperAdmin(
  prisma: PrismaClient,
  hasher: PasswordHasher,
  input: { email: string; displayName: string; password: string },
  now: Date,
): Promise<{ id: string; email: string }> {
  const email = normalizeEmail(input.email)
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) throw new CliRefusal('Enter a valid email address.')
  if (!isPrivilegedEmail(email)) throw new CliRefusal(`The Super Admin must use an address ending in ${PRIVILEGED_EMAIL_SUFFIX} (reserved namespace for privileged accounts).`)
  const displayName = input.displayName.trim()
  if (!displayName) throw new CliRefusal('Enter a display name.')
  const problems = checkPasswordPolicy(input.password, email)
  if (problems.length > 0) throw new CliRefusal(`${passwordPolicyError(problems).message}: ${problems.join(', ')}`)
  const passwordHash = await hasher.hash(input.password)
  return prisma.$transaction(async tx => {
    if ((await tx.staffUser.count({ where: { role: 'SUPER_ADMIN' } })) > 0) throw new CliRefusal('A Super Admin already exists. Create further accounts from the Admin Portal API.')
    if (await tx.staffUser.findUnique({ where: { email }, select: { id: true } })) throw new CliRefusal('A staff account with this email already exists.')
    const staff = await tx.staffUser.create({
      data: { email, displayName, role: 'SUPER_ADMIN', status: 'ACTIVE', passwordHash, mustChangePassword: true, passwordChangedAt: now, createdAt: now },
    })
    await recordAudit(tx, { at: now, category: 'SECURITY', type: 'staff_created', outcome: 'success', subject: { type: 'STAFF', id: staff.id }, details: { role: 'SUPER_ADMIN', via: 'cli' } })
    return { id: staff.id, email: staff.email }
  })
}

/** Removes the 2FA enrolment of a Super Admin (last-resort recovery) and ends all of their sessions. */
export async function resetSuperAdminMfa(prisma: PrismaClient, emailInput: string, now: Date): Promise<void> {
  const email = normalizeEmail(emailInput)
  await prisma.$transaction(async tx => {
    const staff = await tx.staffUser.findUnique({ where: { email } })
    if (!staff || staff.role !== 'SUPER_ADMIN') throw new CliRefusal('No Super Admin with this email.')
    await tx.mfaRecoveryCode.deleteMany({ where: { staffId: staff.id } })
    await tx.staffMfa.deleteMany({ where: { staffId: staff.id } })
    await clearAllForAccount(tx, staff.id)
    await revokeAllSessions(tx, now, { subjectType: 'STAFF', staffId: staff.id }, 'mfa_reset')
    await recordAudit(tx, { at: now, category: 'SECURITY', type: 'mfa_reset', outcome: 'success', subject: { type: 'STAFF', id: staff.id }, details: { via: 'cli' } })
  })
}

/**
 * Deletes sessions and account links that can never be used again (expired or revoked/used more than a day
 * ago). Audit events are never touched.
 */
export async function cleanupExpired(prisma: PrismaClient, now: Date): Promise<{ sessions: number; tokens: number }> {
  const cutoff = new Date(now.getTime() - 24 * 60 * 60_000)
  const sessions = await prisma.session.deleteMany({ where: { OR: [{ absoluteExpiresAt: { lt: cutoff } }, { revokedAt: { lt: cutoff } }] } })
  const tokens = await prisma.accountToken.deleteMany({ where: { OR: [{ expiresAt: { lt: cutoff } }, { usedAt: { lt: cutoff } }] } })
  return { sessions: sessions.count, tokens: tokens.count }
}
